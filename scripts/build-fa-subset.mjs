// Generates a Font Awesome subset (fonts + CSS) containing only the icons actually
// used by the web app, replacing the full all.min.css (~6000 icons + ~1 MB fonts).
// Run with: npm run build:fa  (re-run whenever the set of used icons changes).
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { fontawesomeSubset } from "fontawesome-subset";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const webSrc = join(root, "apps/web/src");
const faPkg = join(root, "node_modules/@fortawesome/fontawesome-free");
const fontsOutDir = join(webSrc, "assets/fa");
const cssOutFile = join(webSrc, "styles/fa-subset.css");

// 1. Collect every "fa-solid fa-x" / "fa-brands fa-x" reference in the source.
const collectIcons = () => {
  const solid = new Set();
  const brands = new Set();
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      const st = statSync(full);
      if (st.isDirectory()) {
        if (entry === "assets" || entry === "node_modules") continue;
        walk(full);
      } else if (/\.(ts|html|css)$/.test(entry)) {
        const text = readFileSync(full, "utf8");
        for (const m of text.matchAll(/fa-solid\s+fa-([a-z0-9-]+)/g)) solid.add(m[1]);
        for (const m of text.matchAll(/fa-brands\s+fa-([a-z0-9-]+)/g)) brands.add(m[1]);
      }
    }
  };
  walk(webSrc);
  return { solid: [...solid].sort(), brands: [...brands].sort() };
};

const { solid, brands } = collectIcons();
console.log(`used icons -> solid: ${solid.length}, brands: ${brands.length}`);

// 2. Generate subset webfonts (woff2 only) for the used icons.
mkdirSync(fontsOutDir, { recursive: true });
await fontawesomeSubset({ solid, brands }, fontsOutDir, { targetFormats: ["woff2"] });

// 3. Build the CSS: base rules + @font-face (subset) + only the used icon glyphs.
const allCss = readFileSync(join(faPkg, "css/all.min.css"), "utf8");

// Extract per-icon content rules (".fa-name:before{content:\"\\fxxx\"}") and remove them
// from the base; keep only the used ones.
const usedNames = new Set([...solid, ...brands]);
// FA6 emits one custom-property rule per glyph, sharing a selector with its aliases,
// e.g. `.fa-bars,.fa-navicon{--fa:"\f0c9"}`. Keep a rule if any of its `.fa-*`
// selectors is an icon we use.
const iconRuleRe = /(\.fa-[a-z0-9-]+(?:,\.fa-[a-z0-9-]+)*)\{--fa:"\\[^"]*"[^}]*\}/g;
const usedIconRules = [];
const baseCss = allCss.replace(iconRuleRe, (full, selector) => {
  const names = [...selector.matchAll(/\.fa-([a-z0-9-]+)/g)].map((m) => m[1]);
  if (names.some((name) => usedNames.has(name))) usedIconRules.push(full);
  return ""; // drop every per-glyph rule from the base, re-add only the used ones
});

// Strip every @font-face from the base; we re-add subset ones pointing at our fonts.
const baseWithoutFonts = baseCss.replace(/@font-face\{[^}]*\}/g, "");

const fontFaces = `@font-face{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:900;font-display:block;src:url(../assets/fa/fa-solid-900.woff2) format("woff2")}
@font-face{font-family:"Font Awesome 6 Brands";font-style:normal;font-weight:400;font-display:block;src:url(../assets/fa/fa-brands-400.woff2) format("woff2")}`;

const out = `/* AUTO-GENERATED by scripts/build-fa-subset.mjs — do not edit by hand.
 * Subset of Font Awesome Free with only the ${usedNames.size} icons used by the app.
 * Re-run \`npm run build:fa\` after adding/removing icons. */
${fontFaces}
${baseWithoutFonts.trim()}
${usedIconRules.join("\n")}
`;

mkdirSync(dirname(cssOutFile), { recursive: true });
writeFileSync(cssOutFile, out);
console.log(`wrote ${relative(root, cssOutFile)} (${(out.length / 1024).toFixed(1)} kB, ${usedIconRules.length} icon glyphs)`);
console.log(`wrote subset fonts to ${relative(root, fontsOutDir)}`);
